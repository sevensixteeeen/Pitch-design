"""Turn tokens.json into tokens.css (plain CSS variables) and tailwind.theme.css
(Tailwind v4 theme mapping). Standard library only.

    python build_tokens.py tokens.json

Run contrast.py first. Never edit the two .css files by hand: change
tokens.json and run this again.
"""

import json
import sys
from pathlib import Path

# token role -> Tailwind colour name, so components write `bg-surface text-muted`.
# "bg" and "text" get other names because `bg-bg` and `text-text` read badly.
TAILWIND_COLOR = {
    "bg": "app",
    "text": "fg",
    "text-muted": "muted",
    "border-input": "input",
}

HEADER = "/* GENERATED by build_tokens.py from tokens.json. Do not edit by hand. */\n"


def css_vars(tokens):
    lines = []
    for role, value in tokens["color"].items():
        lines.append(f"  --tk-color-{role}: {value};")
    lines.append(f"  --tk-color-scrim: {tokens['scrim']};")
    for name, stack in tokens["font"].items():
        lines.append(f"  --tk-font-{name}: {stack};")
    for name, t in tokens["type"].items():
        lines.append(f"  --tk-text-{name}: {t['size']}px;")
        lines.append(f"  --tk-text-{name}-line: {t['line']}px;")
        lines.append(f"  --tk-text-{name}-weight: {t['weight']};")
    for i, px in enumerate(tokens["space"]):
        lines.append(f"  --tk-space-{i}: {px}px;")
    for name, px in tokens["radius"].items():
        lines.append(f"  --tk-radius-{name}: {px}px;")
    for name, value in tokens["shadow"].items():
        lines.append(f"  --tk-shadow-{name}: {value};")
    for name, value in tokens["motion"].items():
        lines.append(f"  --tk-motion-{name}: {value};")
    for name, px in tokens["layout"].items():
        lines.append(f"  --tk-layout-{name}: {px}px;")
    return HEADER + ":root {\n" + "\n".join(lines) + "\n}\n"


def tailwind_theme(tokens):
    lines = [
        "  /* only our tokens exist: no default palette, so raw colours like bg-blue-500 fail */",
        "  --color-*: initial;",
        "  --radius-*: initial;",
        "  --shadow-*: initial;",
    ]
    for role in tokens["color"]:
        name = TAILWIND_COLOR.get(role, role)
        lines.append(f"  --color-{name}: var(--tk-color-{role});")
    lines.append("  --color-scrim: var(--tk-color-scrim);")
    for name in tokens["font"]:
        lines.append(f"  --font-{name}: var(--tk-font-{name});")
    for name in tokens["type"]:
        lines.append(f"  --text-{name}: var(--tk-text-{name});")
        lines.append(f"  --text-{name}--line-height: var(--tk-text-{name}-line);")
        lines.append(f"  --text-{name}--font-weight: var(--tk-text-{name}-weight);")
    # Tailwind spacing is a multiple of one base unit: p-1 = 4px, p-4 = 16px
    lines.append(f"  --spacing: {tokens['space'][1]}px;")
    for name in tokens["radius"]:
        lines.append(f"  --radius-{name}: var(--tk-radius-{name});")
    for name in tokens["shadow"]:
        lines.append(f"  --shadow-{name}: var(--tk-shadow-{name});")
    lines.append("  --ease-standard: var(--tk-motion-ease);")
    for name, px in tokens["breakpoints"].items():
        lines.append(f"  --breakpoint-{name}: {px}px;")
    return (
        HEADER
        + '/* Import after tokens.css:  @import "tailwindcss"; @import "./tokens.css"; @import "./tailwind.theme.css"; */\n'
        + "@theme inline {\n" + "\n".join(lines) + "\n}\n"
    )


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    src = Path(argv[1])
    tokens = json.loads(src.read_text(encoding="utf-8"))
    (src.parent / "tokens.css").write_text(css_vars(tokens), encoding="utf-8")
    (src.parent / "tailwind.theme.css").write_text(tailwind_theme(tokens), encoding="utf-8")
    print(f"wrote {src.parent / 'tokens.css'} and {src.parent / 'tailwind.theme.css'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
